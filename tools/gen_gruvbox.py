#!/usr/bin/env python3
"""Generates lib/data/res/gruvbox_palettes.g.dart from the reference theme.

The reference is Clementine-Miles/ServerBox_Gruvbox_Theme at REVISION: its
`tools/generate.py` derives every Material role (accessible text tones,
containers, fixed roles) from the Gruvbox and Gruvbox Material palettes. This
script imports that module from a checkout and writes the resulting roles as a
plain Dart table, so the app needs no theme package, network or parsing at run
time.

    git clone https://github.com/Clementine-Miles/ServerBox_Gruvbox_Theme ref
    git -C ref checkout <REVISION>
    python3 tools/gen_gruvbox.py ref
"""
import importlib.util
import sys
from pathlib import Path

REVISION = 'd5089d64e7341d76fc538e57590d1b1adcea8ab4'
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'lib/data/res/gruvbox_palettes.g.dart'

ROLES = [
    'primary', 'onPrimary', 'primaryContainer', 'onPrimaryContainer',
    'primaryFixed', 'primaryFixedDim', 'onPrimaryFixed', 'onPrimaryFixedVariant',
    'secondary', 'onSecondary', 'secondaryContainer', 'onSecondaryContainer',
    'secondaryFixed', 'secondaryFixedDim', 'onSecondaryFixed', 'onSecondaryFixedVariant',
    'tertiary', 'onTertiary', 'tertiaryContainer', 'onTertiaryContainer',
    'tertiaryFixed', 'tertiaryFixedDim', 'onTertiaryFixed', 'onTertiaryFixedVariant',
    'error', 'onError', 'errorContainer', 'onErrorContainer',
    'surface', 'onSurface', 'surfaceDim', 'surfaceBright',
    'surfaceContainerLowest', 'surfaceContainerLow', 'surfaceContainer',
    'surfaceContainerHigh', 'surfaceContainerHighest', 'onSurfaceVariant',
    'outline', 'outlineVariant', 'shadow', 'scrim',
    'inverseSurface', 'onInverseSurface', 'inversePrimary',
]
HUES = ('red', 'orange', 'yellow', 'green', 'aqua', 'blue', 'purple')


def main(ref: Path) -> None:
    spec = importlib.util.spec_from_file_location('ref_generate', ref / 'tools/generate.py')
    gen = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(gen)

    def hexes(values):
        return ', '.join(f'0xFF{v}' for v in values)

    lines = [
        '// GENERATED by tools/gen_gruvbox.py from Clementine-Miles/ServerBox_Gruvbox_Theme',
        f'// at {REVISION}. Do not edit by hand.',
        '//',
        '// Gruvbox palette: morhetz/gruvbox (MIT/X11, Pavel Pertsev).',
        '// Gruvbox Material palette: sainnhe/gruvbox-material (MIT, (c) 2020 sainnhe).',
        '// Role derivation: ServerBox_Gruvbox_Theme (MIT, (c) 2026 milesclem contributors).',
        '// Full notices: THIRD_PARTY_NOTICES.md.',
        '',
        'part of \'gruvbox.dart\';',
        '',
        '/// The Material roles, in [_roleOrder] order.',
        f'const _roleOrder = <String>[{", ".join(repr(r) for r in ROLES)}];',
        '',
        '/// Red, orange, yellow, green, aqua, blue, purple: the canonical anchors.',
        'const _anchors = <(GruvboxFamily, Brightness), List<int>>{',
    ]
    fams = {'original': 'GruvboxFamily.gruvbox', 'material': 'GruvboxFamily.material'}
    for fam, dart in fams.items():
        for mode in ('dark', 'light'):
            c = gen.colors(fam, mode)
            b = 'Brightness.dark' if mode == 'dark' else 'Brightness.light'
            lines.append(f'  ({dart}, {b}): [{hexes(c[h] for h in HUES)}],')
    lines += ['};', '', '/// Every variant\'s roles.', 'const _schemes = <(GruvboxFamily, GruvboxContrast, GruvboxAccent, Brightness), List<int>>{']
    for fam, dart in fams.items():
        for level in gen.levels(fam):
            for accent in ('green', 'blue'):
                for mode in ('dark', 'light'):
                    p = gen.palette(fam, level, accent, mode)
                    vals = []
                    for r in ROLES:
                        v = p[r]
                        vals.append('0xFF' + v if isinstance(v, str) else f'0x{v:08X}')
                    b = 'Brightness.dark' if mode == 'dark' else 'Brightness.light'
                    lines.append(
                        f'  ({dart}, GruvboxContrast.{level}, GruvboxAccent.{accent}, {b}): '
                        f'[{", ".join(vals)}],')
    lines += ['};', '']
    OUT.write_text('\n'.join(lines))


if __name__ == '__main__':
    main(Path(sys.argv[1]))
